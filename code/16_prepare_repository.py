"""Prepare a standalone publication folder; never publish or redistribute PISA microdata."""
from pathlib import Path
import shutil, hashlib, json, zipfile
ROOT=Path(__file__).resolve().parents[1]
DEST=ROOT/'connected-but-lonelier' if (ROOT/'connected-but-lonelier').exists() else ROOT/'publish_repository'
TEX=ROOT/'latex' if (ROOT/'latex/main.tex').exists() else ROOT/'Paper1_PISA2022'
DEST.mkdir(exist_ok=True)
def copy(source,relative):
    target=DEST/relative; target.parent.mkdir(parents=True,exist_ok=True); shutil.copy2(source,target)
for name in ['requirements.txt','requirements-lock.txt','UPGRADE_REPORT.md','PEER_REVIEW_RESPONSE.md']:
    if not (ROOT/name).exists(): continue
    copy(ROOT/name,Path(name))
for source in (ROOT/'code').glob('*.py'): copy(source,Path('code')/source.name)
for source in TEX.rglob('*'):
    if source.is_file() and not any(p.startswith('.') for p in source.relative_to(TEX).parts) and source.suffix in ['.tex','.bib','.pdf','.png','.ps1','.bbl','.md','.txt']:
        copy(source,Path('latex')/source.relative_to(TEX))
for directory in (ROOT/'outputs').glob('results*'):
    if directory.is_dir():
        for source in directory.glob('*'):
            if source.is_file() and source.suffix in ['.csv','.json']: copy(source,source.relative_to(ROOT))
for name in ['policy','worldbank','who']:
    for source in (ROOT/'data/raw'/name).rglob('*'):
        if source.is_file() and source.suffix in ['.csv','.json','.md','.txt']: copy(source,source.relative_to(ROOT))
for cycle in ['pisa2012','pisa2015','pisa2018','pisa2022/sch']:
    (DEST/'data/raw'/cycle).mkdir(parents=True,exist_ok=True)
data_readme='''# Data acquisition

The student/school microdata and processed student parquets are not distributed in this repository. Obtain them from the original sources before rerunning extraction; aggregate result CSVs are included for manuscript inspection.

| Input path | Source |
| --- | --- |
| `raw/pisa2012/pisa2012.csv` | OECD PISA 2012 public file converted to labelled CSV; the conversion used here is https://s3.amazonaws.com/udacity-hosted-downloads/ud507/pisa2012.csv.zip (extract CSV). Consult the OECD questionnaire/codebook to verify labels. |
| `raw/pisa2015/PUF_SPSS_COMBINED_CMB_STU_QQQ.zip` | https://webfs.oecd.org/pisa/PUF_SPSS_COMBINED_CMB_STU_QQQ.zip |
| `raw/pisa2018/SPSS_STU_QQQ.zip` | https://webfs.oecd.org/pisa2018/SPSS_STU_QQQ.zip |
| `raw/pisa2022/STU_QQQ_SPSS.zip` and extracted `CY08MSP_STU_QQQ.SAV` | https://webfs.oecd.org/pisa2022/STU_QQQ_SPSS.zip |
| `raw/pisa2022/SCH_QQQ_SPSS.zip`, SAV extracted under `raw/pisa2022/sch/` | https://webfs.oecd.org/pisa2022/SCH_QQQ_SPSS.zip |

Official dataset landing page: https://www.oecd.org/en/data/datasets/pisa-2022-database.html . Earlier cycles and their documentation are linked by OECD. Retain original filenames/case. `01_extract.py` reads the 2022 ZIP and `05_trend_extract.py` reads the extracted 2022 SAV. Raw datasets are several GB; use enough disk/memory. No API credentials are required for these public sources.

Small context snapshots (`raw/worldbank/`, `raw/who/`) and policy coding/evidence (`raw/policy/`) are included; their providers' terms continue to apply. See source URLs and retrieval dates in those files. Population suicide indicators describe all ages, not the PISA student sample. The unused failed OWID download is not included.
'''
(DEST/'data/README.md').write_text(data_readme,encoding='utf-8')
readme=(ROOT/'README.md').read_text(encoding='utf-8')
readme=readme.replace('paper1_PISA2022/','repository/').replace('  archive/       Bản nháp cũ\n','')
readme=readme.replace('Paper1_PISA2022/', 'latex/').replace('`Paper1_PISA2022/`','`latex/`')
readme=readme.replace('Thư mục `data/raw/owid_gbd/` kế thừa chỉ chứa lỗi tải 403 và không dùng trong phân tích.','Xem `data/README.md` để tải dữ liệu cá nhân từ nguồn gốc; thư mục này chỉ kèm kết quả tổng hợp và dữ liệu bối cảnh nhỏ.')
readme=readme.replace('`publish_repository/` là thư mục độc lập để bạn push sau; không có repo URL giả và không tự đăng lên mạng.','Đây là thư mục độc lập để bạn push sau; chưa có URL công khai. Dữ liệu PISA cá nhân không kèm; xem `data/README.md`.')
readme=readme.replace('`connected-but-lonelier/` là thư mục độc lập để bạn push sau; không có repo URL giả và không tự đăng lên mạng.','Thư mục này sẵn để push; chưa có URL công khai được xác nhận.')
readme+='''
## Running only the upgrade on existing processed inputs

Place `pisa_trend_2012_2022.parquet` and `pisa22_analysis.parquet` in `outputs/` (generated by extraction), then run `12_upgrade_analysis.py`, `14_upgrade_tables.py` and `15_print_shap.py`. `--calibration-only` resumes only the reading/calibration stage. The full sequence above ensures that older tables are generated **before** the upgrade tables, so the updated DFL table is not overwritten. `13_reference_audit.py` is an optional online metadata audit; saved publisher records accompany the current manuscript.

All computations execute locally. These survey/LightGBM analyses use CPU, with four threads for the upgrade; they do not require GPU. Code does not publish anything. `16_prepare_repository.py` is the packaging helper and is not part of the analysis sequence.

## Before public release

Fill author/affiliation/email/CRediT fields, choose a code license, review the AI declaration and policy coding evidence, then push this folder to your chosen repository. Add the resulting URL (and any Zenodo DOI) to `latex/main.tex` under Data and code availability and rebuild. No placeholder is presented as a working URL. Data-provider terms apply separately. Package SHA256 checksums are in `MANIFEST_SHA256.json`.
'''
(DEST/'README.md').write_text(readme,encoding='utf-8')
(DEST/'.gitignore').write_text('''# Runtime, raw microdata and large processed inputs
.venv/
__pycache__/
*.pyc
data/raw/pisa*/
outputs/*.parquet
outputs/*.log
latex/.latex-cache/
*.aux
*.log
*.out
*.bcf
*.run.xml
*.blg
*.fdb_latexmk
*.fls
publish_repository/
*.zip
''',encoding='utf-8')
files=sorted(p for p in DEST.rglob('*') if p.is_file() and p.name!='MANIFEST_SHA256.json' and '.git' not in p.relative_to(DEST).parts and not any(x.startswith('.') and x!='.gitignore' for x in p.relative_to(DEST).parts))
manifest={str(p.relative_to(DEST)).replace('\\','/'):hashlib.sha256(p.read_bytes()).hexdigest() for p in files}
(DEST/'MANIFEST_SHA256.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
package=ROOT/'paper1_publish_repository.zip'
with zipfile.ZipFile(package,'w',zipfile.ZIP_DEFLATED) as archive:
    for source in files+[DEST/'MANIFEST_SHA256.json']:
        archive.write(source,Path('paper1_repository')/source.relative_to(DEST))
print('Ready:',DEST,'files',len(files)+1,'ZIP bytes',package.stat().st_size)
